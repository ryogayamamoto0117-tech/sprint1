package com.example.sprint1;

public class Record {

    private Long id;
    private String topic;
    private String memo;

public Long getId() {
    return id;
}

public void setId(Long id) {
    this.id = id;
}

public String getTopic() {
    return topic;
}

public void setTopic(String topic) {
    this.topic = topic;
}

public String getMemo() {
    return memo;
}

public void setMemo(String memo) {
    this.memo = memo;
}

}